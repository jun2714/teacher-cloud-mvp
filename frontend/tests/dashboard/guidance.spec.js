import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'

let preview
test.beforeEach(async ({ context }) => {
  preview = JSON.parse(readFileSync(new URL('../../../backend/data/dashboard-browser-session.json', import.meta.url), 'utf8'))
  await context.addCookies([{ name: 'sessionid', value: preview.sessionid, domain: '127.0.0.1', path: '/', httpOnly: true, sameSite: 'Lax' }])
})

test('leader reads a real artifact, drafts guidance, teacher responds, and leader follows up', async ({ page, context }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1672, height: 1050 })
  await page.goto(`/admin/learning/lessonplan/${preview.plan_id}/change/`)
  await expect(page.getByRole('article', { name: '教学设计正文' })).toBeVisible()
  await expect(page.locator('.reading-toc a').first()).toBeVisible()
  await expect(page.locator('textarea')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)).toBe(false)
  await page.screenshot({ path: '../output/admin-document-modern.png', animations: 'disabled' })
  await page.getByRole('button', { name: '深色', exact: true }).click()
  await page.screenshot({ path: '../output/admin-document-modern-dark.png', animations: 'disabled' })
  await page.getByRole('button', { name: '浅色', exact: true }).click()
  await page.goto(`/admin/learning/researchreport/${preview.report_id}/change/`)
  await expect(page.locator('.reading-document')).toBeVisible()
  await expect(page.locator('textarea, select[multiple]')).toHaveCount(0)
  await page.screenshot({ path: '../output/admin-report-modern.png', animations: 'disabled' })
  await page.goto(`/admin/learning/lessonplan/${preview.plan_id}/change/`)
  await page.getByRole('link', { name: '给予指导', exact: true }).click()
  await page.getByLabel('值得肯定').fill('教学目标与文本内容联系紧密。')
  await page.getByLabel('改进建议').fill('在朗读后增加一次基于量规的同伴互评，帮助学生看见自己的进步。')
  await page.getByLabel('下一步行动').fill('下一次课尝试两人互评，并记录学生的反馈。')
  await page.screenshot({ path: '../output/admin-feedback-editor.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(page.locator('[data-feedback-status="draft"]')).toBeVisible()
  await page.getByRole('link', { name: '继续编辑', exact: true }).click()
  await page.getByRole('button', { name: '发送指导', exact: true }).click()
  await expect(page.locator('[data-feedback-status="sent"]')).toBeVisible()
  const response = await page.request.get('/api/teaching-feedback/', { headers: { Authorization: `Bearer ${preview.teacher_access}` } })
  expect(response.ok()).toBe(true)
  const feedback = (await response.json()).results.find(item => item.suggestions.includes('基于量规的同伴互评'))
  expect(feedback).toBeTruthy()
  const teacherPage = await context.newPage()
  await teacherPage.addInitScript(token => localStorage.setItem('access_token', token), preview.teacher_access)
  await teacherPage.setViewportSize({ width: 390, height: 844 })
  await teacherPage.goto(`http://127.0.0.1:6062/guidance/${feedback.id}`)
  await expect(teacherPage.getByRole('heading', { name: '改进建议', exact: true })).toBeVisible()
  await teacherPage.screenshot({ path: '../output/teacher-guidance-mobile.png', fullPage: true, animations: 'disabled' })
  await teacherPage.getByLabel('落实说明', { exact: true }).fill('已在课堂开展同伴互评，学生能够根据量规给出具体建议。下一次将简化评价维度。')
  await teacherPage.getByRole('button', { name: '提交落实说明', exact: true }).click()
  await expect(teacherPage.getByRole('heading', { name: '我的落实说明' })).toBeVisible()
  await page.goto(`/admin/teaching/teachers/${preview.profile_id}/`)
  await expect(page.locator('.teacher-response')).toContainText('已在课堂开展同伴互评')
  await page.screenshot({ path: '../output/admin-teacher-growth.png', fullPage: true, animations: 'disabled' })
  await page.goto('/admin/teaching/')
  await expect(page.getByRole('heading', { name: '教研指导工作台', exact: true })).toBeVisible()
  await page.screenshot({ path: '../output/admin-guidance-workbench.png', fullPage: true, animations: 'disabled' })
  await expect(page.locator('.guidance-teachers-table')).toBeVisible()
  for (const width of [1280, 800, 390]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)).toBe(false)
  }
  await page.goto(`/admin/learning/lessonplan/${preview.plan_id}/change/`)
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)).toBe(false)
  await page.screenshot({ path: '../output/admin-reading-mobile.png', animations: 'disabled' })
  await teacherPage.close()
  expect(errors).toEqual([])
})
